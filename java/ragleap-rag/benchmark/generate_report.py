#!/usr/bin/env python3
"""
Builds RESULTS.md from the raw result files of the cross-backend benchmark (issue #565).

Usage: python3 generate_report.py [SRC_DIR]      (default /tmp/bench)
Copies the raw JSON from SRC_DIR into ./results/ and writes ./RESULTS.md from those copies,
so every number in the report can be traced to a committed file.
"""
import json
import os
import re
import shutil
import sys

SRC = sys.argv[1] if len(sys.argv) > 1 else "/tmp/bench"
HERE = os.path.dirname(os.path.abspath(__file__))
RES = os.path.join(HERE, "results")
BACKENDS = ["faiss", "pgvector", "qdrant", "weaviate"]
LABEL = {"faiss": "FAISS", "pgvector": "pgvector", "qdrant": "Qdrant", "weaviate": "Weaviate"}


def copy_inputs():
    os.makedirs(RES, exist_ok=True)
    for sub, dest in (("results", "retrieval-before-score-fixes"), ("results-after", "retrieval-after-score-fixes")):
        d = os.path.join(RES, dest)
        os.makedirs(d, exist_ok=True)
        for name in ["exact-float64.json"] + [b + ".json" for b in BACKENDS]:
            shutil.copy(os.path.join(SRC, sub, name), os.path.join(d, name))
    shutil.copy(os.path.join(SRC, "results-matrix-before", "failure-matrix.json"), os.path.join(RES, "failure-matrix-before-fixes.json"))
    shutil.copy(os.path.join(SRC, "results-matrix-after", "failure-matrix.json"), os.path.join(RES, "failure-matrix-after-fixes.json"))
    shutil.copy(os.path.join(SRC, "environment.json"), os.path.join(RES, "environment.json"))


def load(*parts):
    return json.load(open(os.path.join(RES, *parts), encoding="utf-8"))


def esc(s):
    return s.replace("|", "\\|").replace("\n", " ")


def norm(s):
    s = re.sub(r"(?i)matrix_?\d+x\d+", "matrix_N", s)
    return re.sub(r"EXC \w+(?:Exception|Error): (?:ERROR: )?", "EXC: ", s)


def clip(s, n=200):
    return s if len(s) <= n else s[:n] + "..."


NOTES = {
    "duplicate-insert": "FAISS and pgvector accept a second chunk with the same document and chunk index (both are returned by a search). Qdrant and Weaviate reject it, because their point ids are derived from documentId:chunkIndex and their local table has a unique key on it. A duplicate document id is rejected by all four.",
    "wrong-dimension-query": "pgvector raises an error; FAISS, Qdrant and Weaviate return an empty list.",
    "zero-vector": "pgvector returns nothing for an all-zero vector (cosine similarity is undefined for it); the other three return it with score 0.5. Embedding models do not normally produce zero vectors.",
    "server-unreachable": "pgvector raises the connection pool's unchecked PoolInitializationException; Qdrant and Weaviate raise SQLException. Callers should catch RuntimeException as well as SQLException for pgvector connection failures. FAISS runs in-process and has no server.",
}

FIXED_BY = {
    "empty-collection-search": "#585", "filter-on-unknown-key": "#585",
    "wrong-dimension-insert": "#584", "failed-insert-then-retry": "#584 and #585",
}


def main():
    copy_inputs()
    exact = load("retrieval-after-score-fixes", "exact-float64.json")
    before = {b: load("retrieval-before-score-fixes", b + ".json") for b in BACKENDS}
    after = {b: load("retrieval-after-score-fixes", b + ".json") for b in BACKENDS}
    env = load("environment.json")
    mb = {c["id"]: c for c in load("failure-matrix-before-fixes.json")["cases"]}
    ma = load("failure-matrix-after-fixes.json")["cases"]

    identical, differing, fixed = [], [], []
    for c in ma:
        vals = {b: norm(c["results"][b]) for b in BACKENDS if not c["results"][b].startswith("N/A")}
        (identical if len(set(vals.values())) == 1 and len(vals) == 4 else differing).append(c)
        ch = [b for b in BACKENDS if norm(mb[c["id"]]["results"][b]) != norm(c["results"][b])]
        if ch:
            fixed.append((c, ch))

    o = []
    o.append("# Cross-backend benchmark and failure-mode matrix (Java port)")
    o.append("")
    o.append("Answers issue #565: do the Java vector backends return comparable results, and how do they behave on edge cases? "
             "Run on %s. Every number below is generated by `generate_report.py` from the raw files in `results/`." % env["date"])
    o.append("")
    o.append("## Summary")
    o.append("")
    o.append("- **Retrieval is identical** on FAISS, pgvector, Qdrant and Weaviate: the same top-10 documents for all %d queries (overlap@10 = 1.000 against an exact float64 scan), and each finds the source paragraph exactly as often as the exact scan." % after["faiss"]["queries"])
    o.append("- The benchmark found **two score-scale bugs** (FAISS and Weaviate returned raw cosine in [-1, 1] while pgvector and Qdrant return [0, 1]); both are fixed (#574, #576).")
    o.append("- The failure-mode matrix (%d cases x 4 backends) found **three more bugs** in Weaviate, FAISS and Qdrant, all fixed (#584, #585). After the fixes, %d cases behave the same on all four backends and %d differ in documented ways." % (len(ma), len(identical), len(differing)))
    o.append("- **Not covered:** Milvus and Pinecone (no infrastructure to run them live; they are tested against HTTP stubs only), and approximate-search recall at scale (see Limits).")
    o.append("")
    o.append("## Method")
    o.append("")
    o.append("- **Data:** SQuAD v1.1 dev set (CC BY-SA 4.0). Every 7th paragraph is a document (%d documents); the first question of 60 of them is a query whose gold document is the paragraph it was written from." % after["faiss"]["docs"])
    o.append("- **Vectors:** embedded once with %s, then the same vectors are stored in every backend, so embedding noise cannot affect the comparison." % env["embeddingModel"])
    o.append("- **Ground truth:** an exact float64 cosine scan computed in the test itself; no backend is used as its own reference.")
    o.append("- **Metrics:** overlap@10 (share of the exact top-10 returned), top-1 agreement, gold hit@k (does the backend find the source paragraph), the score range, and the deviation of each returned score from (cosine + 1) / 2.")
    o.append("- **Environment:** Java `%s`; Qdrant %s; Weaviate %s; pgvector %s on Postgres; %s CPU, %s GB RAM." % (env["java"], env["qdrant"], env["weaviate"], env["pgvector"], env["cpus"], env["ramGb"]))
    o.append("")
    o.append("## Retrieval results (after the fixes)")
    o.append("")
    o.append("Exact float64 scan: gold hit@1 / @5 / @10 = %.3f / %.3f / %.3f." % (exact["goldHit1"], exact["goldHit5"], exact["goldHit10"]))
    o.append("")
    o.append("| Backend | overlap@10 | top-1 agreement | gold hit@1 / @5 / @10 | score range | deviation from (cosine+1)/2, mean / max | median latency |")
    o.append("|---|---|---|---|---|---|---|")
    for b in BACKENDS:
        r = after[b]
        o.append("| %s | %.3f | %.3f | %.3f / %.3f / %.3f | %.3f to %.3f | %.5f / %.5f | %.1f ms |" % (
            LABEL[b], r["overlapAt10"], r["top1Agreement"], r["goldHit1"], r["goldHit5"], r["goldHit10"],
            r["scoreMin"], r["scoreMax"], r["scoreDevMean"], r["scoreDevMax"], r["latencyMedianMs"]))
    o.append("")
    o.append("Latency is indicative only: one shared CPU with heavy steal time, a %d-document corpus, and run-to-run variation (Weaviate's p95 varied several-fold between runs)." % after["faiss"]["docs"])
    o.append("")
    o.append("## Score scale: before and after the fixes")
    o.append("")
    o.append("| Backend | score range before | deviation before (mean / max) | score range after | deviation after (mean / max) |")
    o.append("|---|---|---|---|---|")
    for b in BACKENDS:
        x, y = before[b], after[b]
        o.append("| %s | %.3f to %.3f | %.5f / %.5f | %.3f to %.3f | %.5f / %.5f |" % (
            LABEL[b], x["scoreMin"], x["scoreMax"], x["scoreDevMean"], x["scoreDevMax"],
            y["scoreMin"], y["scoreMax"], y["scoreDevMean"], y["scoreDevMax"]))
    o.append("")
    o.append("Before the fixes, FAISS and Weaviate returned raw cosine similarity; a score threshold meant different things on different backends. Retrieval order was unaffected (the change is monotonic).")
    o.append("")
    o.append("## Failure-mode matrix")
    o.append("")
    o.append("Each case runs on a fresh collection and records what happens (result or exception) without asserting, so differences show up. "
             "In the comparison, exception class names are ignored (pgvector's driver raises a PSQLException, a subclass of SQLException).")
    o.append("")
    o.append("### Same behaviour on all four backends (%d cases)" % len(identical))
    o.append("")
    o.append("| Case | What was tested | Result |")
    o.append("|---|---|---|")
    for c in identical:
        o.append("| `%s` | %s | %s |" % (c["id"], esc(c["description"]), esc(clip(norm(c["results"]["faiss"]).removeprefix("OK "), 160))))
    o.append("")
    o.append("### Differences that remain (%d cases)" % len(differing))
    o.append("")
    for c in differing:
        o.append("#### `%s`: %s" % (c["id"], c["description"]))
        o.append("")
        o.append("| Backend | Result |")
        o.append("|---|---|")
        for b in BACKENDS:
            o.append("| %s | %s |" % (LABEL[b], esc(clip(c["results"][b]))))
        o.append("")
        if c["id"] in NOTES:
            o.append(NOTES[c["id"]])
            o.append("")
    o.append("### Fixed during this work")
    o.append("")
    for c, ch in fixed:
        o.append("#### `%s` (fixed in %s)" % (c["id"], FIXED_BY.get(c["id"], "see PRs")))
        o.append("")
        for b in ch:
            o.append("- **%s** before: `%s`" % (LABEL[b], esc(clip(mb[c["id"]]["results"][b]))))
            o.append("  after: `%s`" % esc(clip(c["results"][b])))
        o.append("")
    o.append("## Bugs found and fixed")
    o.append("")
    o.append("| Finding | Fix |")
    o.append("|---|---|")
    o.append("| Weaviate returned raw cosine in [-1, 1] | #574 |")
    o.append("| FAISS returned raw cosine in [-1, 1] | #576 |")
    o.append("| FAISS, Qdrant and Weaviate accepted or mishandled a wrong-dimension vector on insert (FAISS stored it silently) | #584 |")
    o.append("| Weaviate raised a GraphQL error when searching an empty collection or filtering on a key no chunk had yet | #585 |")
    o.append("| Qdrant and Weaviate left a local row behind when the server write failed, so the chunk could not be retried | #585 |")
    o.append("")
    o.append("The Python `FaissBackend` and `PineconeBackend` still return raw cosine scores (issue #577).")
    o.append("")
    o.append("## Limits")
    o.append("")
    o.append("- %d documents is small: Qdrant and Weaviate use HNSW indexes, but at this size they behave like an exact scan. This measures integration correctness, score comparability and retrieval quality, **not approximate-search recall at scale**." % after["faiss"]["docs"])
    o.append("- 60 queries from one dataset and one embedding model.")
    o.append("- One known gap: if a server applies a write but the response is lost, retrying the same chunk can still fail on Weaviate.")
    o.append("- Milvus and Pinecone are not benchmarked.")
    o.append("")
    o.append("## Reproduce")
    o.append("")
    o.append("```bash")
    o.append("python3 java/ragleap-rag/benchmark/prepare_dataset.py            # downloads SQuAD, embeds with Ollama, writes /tmp/bench/corpus.json")
    o.append("cd java/ragleap-rag")
    o.append("RAGLEAP_BENCH_DIR=/tmp/bench RAGLEAP_BENCH_BACKENDS=faiss,pgvector,qdrant,weaviate mvn test -Dtest=CrossBackendBenchmarkTest")
    o.append("RAGLEAP_BENCH_DIR=/tmp/bench RAGLEAP_BENCH_BACKENDS=faiss,pgvector,qdrant,weaviate mvn test -Dtest=FailureModeMatrixTest")
    o.append("```")
    o.append("")
    o.append("Needs Qdrant on :6333, Weaviate on :8081 and a Postgres with pgvector and an empty database `ragleap_java_bench` on :5433 (see the test sources for the connection settings).")
    o.append("")
    open(os.path.join(HERE, "RESULTS.md"), "w", encoding="utf-8").write("\n".join(o))
    print("wrote RESULTS.md: identical=%d differing=%d fixed=%d" % (len(identical), len(differing), len(fixed)))


if __name__ == "__main__":
    main()
